// Extracts directory entries (list items) from a docs page's Markdown body. Shared by
// scripts/build-terms-index.mjs (A-Z index), src/pages/directory.json.ts (structured
// export for agents) and src/components/Head.astro (schema.org JSON-LD), so all three
// agree on what an entry is and what anchor it lives at.
//
// The anchor ids must match the ids ./rehype-entry-ids.mjs assigns to each <li> at build
// time, so this replicates the exact same rule: slug the first link's text if the entry
// has one, else the whole list item's text, truncated to 60 chars — using a slugger reset
// per page, in document order, so duplicate-name collisions ("-1" suffixes) land the same
// way here as they do in the real build.
import { unified } from "unified";
import remarkParse from "remark-parse";
import { visit } from "unist-util-visit";
import { toString } from "mdast-util-to-string";
import GithubSlugger from "github-slugger";

// Docs page ids that aren't directory listings — nothing to extract. Pages under
// downloads/ are generated by build-spreadsheets.mjs and hold checklists, not entries.
const NON_DIRECTORY_PAGES = new Set(["404", "contributing", "index-of-terms", "index", "downloads"]);

export function isDirectoryPage(id) {
  return !NON_DIRECTORY_PAGES.has(id) && !id.includes("/");
}

const processor = unified().use(remarkParse);

/**
 * @param {string} body Markdown body (no frontmatter)
 * @returns {Array<{ name: string, anchorId: string, href: string | null,
 *   description: string, category: string[] }>}
 */
export function extractEntries(body) {
  const tree = processor.parse(body);
  const slugger = new GithubSlugger();
  const headings = [];
  const entries = [];

  for (const block of tree.children) {
    if (block.type === "heading") {
      headings.length = block.depth - 1;
      headings[block.depth - 1] = toString(block).trim();
      continue;
    }
    visit(block, "listItem", (node) => {
      let link = null;
      visit(node, "link", (n) => {
        if (!link) link = n;
      });
      let strong = null;
      if (!link) {
        visit(node, "strong", (n) => {
          if (!strong) strong = n;
        });
      }

      const idText = (link ? toString(link) : toString(node)).trim();
      if (!idText) return;
      const anchorId = slugger.slug(idText.slice(0, 60));

      const name = (link ? toString(link) : strong ? toString(strong) : toString(node)).trim();
      // Description is the entry's own paragraph, minus the leading name and its
      // "Name - description" separator; nested sub-entries are extracted separately.
      const paragraph = node.children.find((c) => c.type === "paragraph");
      const text = paragraph ? toString(paragraph, { includeHtml: false }).replace(/\s+/g, " ").trim() : "";
      const description = (text.startsWith(name) ? text.slice(name.length) : text)
        .replace(/^\s*[-–—:]\s*/, "")
        .trim();

      entries.push({
        name,
        anchorId,
        href: link?.url ?? null,
        description,
        category: headings.filter(Boolean),
      });
    });
  }
  return entries;
}
