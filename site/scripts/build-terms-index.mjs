#!/usr/bin/env node
// Generates an A-Z index of every directory entry across all docs pages
// (src/content/docs/*.md, after sync-readme.mjs has regenerated them), each
// linking straight to that entry. Must run *after* sync-readme.mjs, since
// sync-readme wipes and regenerates the whole docs/ directory.
//
// The anchor ids this writes must match the ids ../src/rehype-entry-ids.mjs
// assigns to each <li> at build time, so it replicates the exact same rule:
// slug the first link's text if the entry has one, else the whole list
// item's text, truncated to 60 chars — using a slugger reset per page, in
// document order, so duplicate-name collisions ("-1" suffixes) land the same
// way here as they do in the real build.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { unified } from "unified";
import remarkParse from "remark-parse";
import { visit } from "unist-util-visit";
import { toString } from "mdast-util-to-string";
import GithubSlugger from "github-slugger";

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = resolve(siteDir, "src/content/docs");

// Not directory-listing pages — nothing to index.
const SKIP_FILES = new Set(["contributing.md", "index-of-terms.md", "index.md"]);

function pageUrl(slug) {
  return `/${slug}/`;
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { title: "", body: raw };
  const title = match[1].match(/title:\s*"((?:[^"\\]|\\.)*)"/)?.[1] ?? "";
  return { title, body: raw.slice(match[0].length) };
}

const processor = unified().use(remarkParse);

const entries = [];
for (const file of readdirSync(docsDir).sort()) {
  if (!file.endsWith(".md") || SKIP_FILES.has(file)) continue;
  const slug = file.replace(/\.md$/, "");
  const raw = readFileSync(resolve(docsDir, file), "utf8");
  const { title: pageTitle, body } = parseFrontmatter(raw);
  const tree = processor.parse(body);
  const slugger = new GithubSlugger();

  visit(tree, "listItem", (node) => {
    let link = null;
    visit(node, "link", (n) => {
      if (!link) link = n;
    });
    let strong = null;
    if (!link) {
      visit(node, "strong", (n) => {
        if (!strong) strong = n;
      });
    }

    const idText = (link ? toString(link) : toString(node)).trim();
    if (!idText) return;
    const anchorId = slugger.slug(idText.slice(0, 60));

    const displayName = (link ? toString(link) : strong ? toString(strong) : toString(node)).trim();
    entries.push({ name: displayName, pageTitle, url: `${pageUrl(slug)}#${anchorId}` });
  });
}

entries.sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));

const groups = new Map();
for (const entry of entries) {
  const first = entry.name[0]?.toUpperCase() ?? "";
  const letter = /[A-Z]/.test(first) ? first : "#";
  if (!groups.has(letter)) groups.set(letter, []);
  groups.get(letter).push(entry);
}

const letters = [...groups.keys()].sort((a, b) => (a === "#" ? 1 : b === "#" ? -1 : a.localeCompare(b)));

const body = letters
  .map((letter) => {
    const items = groups
      .get(letter)
      .map((e) => `- [${e.name}](${e.url}) — ${e.pageTitle}`)
      .join("\n");
    return `## ${letter}\n\n${items}`;
  })
  .join("\n\n");

const frontmatter = [
  "---",
  `title: "Index"`,
  `description: "A-Z index of every entry in the directory."`,
  "---",
  "",
  `<!-- Generated by scripts/build-terms-index.mjs from the other src/content/docs pages — do not edit directly. -->`,
  "",
].join("\n");

writeFileSync(resolve(docsDir, "index-of-terms.md"), frontmatter + body + "\n");
console.log(`Wrote index-of-terms.md with ${entries.length} entries.`);
