#!/usr/bin/env node
// Generates an A-Z index of every directory entry across all docs pages
// (src/content/docs/*.md, after sync-readme.mjs has regenerated them), each
// linking straight to that entry. Must run *after* sync-readme.mjs, since
// sync-readme wipes and regenerates the whole docs/ directory.
//
// Entry extraction (and the anchor-id rule it must share with
// ../src/rehype-entry-ids.mjs) lives in ../src/directory-entries.mjs.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractEntries, isDirectoryPage } from "../src/directory-entries.mjs";

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = resolve(siteDir, "src/content/docs");

// Relative, not absolute — index-of-terms.md and e.g. vendors.md are sibling
// top-level docs, so this must climb back out of /index-of-terms/ first. A
// leading "/vendors/" would ignore Astro's configured `base`, which is fine
// on the main site (served at domain root) but 404s on the SignalK plugin
// build, which serves everything under a base path.
function pageUrl(slug) {
  return `../${slug}/`;
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { title: "", body: raw };
  const title = match[1].match(/title:\s*"((?:[^"\\]|\\.)*)"/)?.[1] ?? "";
  return { title, body: raw.slice(match[0].length) };
}

const entries = [];
for (const file of readdirSync(docsDir).sort()) {
  if (!file.endsWith(".md")) continue;
  const slug = file.replace(/\.md$/, "");
  if (!isDirectoryPage(slug)) continue;
  const raw = readFileSync(resolve(docsDir, file), "utf8");
  const { title: pageTitle, body } = parseFrontmatter(raw);
  for (const { name, anchorId } of extractEntries(body)) {
    entries.push({ name, pageTitle, url: `${pageUrl(slug)}#${anchorId}` });
  }
}

entries.sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));

const groups = new Map();
for (const entry of entries) {
  const first = entry.name[0]?.toUpperCase() ?? "";
  const letter = /[A-Z]/.test(first) ? first : "#";
  if (!groups.has(letter)) groups.set(letter, []);
  groups.get(letter).push(entry);
}

const letters = [...groups.keys()].sort((a, b) => (a === "#" ? 1 : b === "#" ? -1 : a.localeCompare(b)));

const body = letters
  .map((letter) => {
    const items = groups
      .get(letter)
      .map((e) => `- [${e.name}](${e.url}) — ${e.pageTitle}`)
      .join("\n");
    return `## ${letter}\n\n${items}`;
  })
  .join("\n\n");

const frontmatter = [
  "---",
  `title: "Index"`,
  `description: "A-Z index of every entry in the directory."`,
  "---",
  "",
  `<!-- Generated by scripts/build-terms-index.mjs from the other src/content/docs pages — do not edit directly. -->`,
  "",
].join("\n");

writeFileSync(resolve(docsDir, "index-of-terms.md"), frontmatter + body + "\n");
console.log(`Wrote index-of-terms.md with ${entries.length} entries.`);
