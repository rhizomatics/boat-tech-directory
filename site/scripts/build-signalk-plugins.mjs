#!/usr/bin/env node
// Generates the SignalK Plugins pages: an index page listing the categories, and a page per
// SignalK App Store category, built from the same live data the App Store itself uses:
//
//   - npm search, for the keywords the App Store searches (name, description, category
//     keywords, last published date)
//   - the SignalK Plugin Registry (https://signalk.org/signalk-plugin-registry/), for the
//     composite score and test results
//
// Categories follow the App Store's rules (see ../src/signalk-categories.mjs). Packages the
// server marks deprecated are left out. `@signalk/` packages also get an "Official" page.
//
// Must run *after* sync-readme.mjs, which wipes src/content/docs/. If the data can't be
// fetched (offline dev, npm outage), it writes a placeholder index page and carries on, so
// the rest of the build still works.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CATEGORIES, DEFAULT_MODULE_CAT_KEYWORDS, DEPRECATED, SIGNALK_GROUPS } from "../src/signalk-categories.mjs";

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = resolve(siteDir, "src/content/docs");
const pagesDir = resolve(docsDir, "signalk-plugins");
// Structured copy of the same data, for agents (linked from llms.txt) and for the pages'
// schema.org JSON-LD (src/components/Head.astro).
const dataPath = resolve(siteDir, "public/signalk-plugins.json");
const SITE = "https://boat-tech-directory.rhizomatics.org.uk";

const SEARCH_KEYWORDS = ["signalk-node-server-plugin", "signalk-embeddable-webapp", "signalk-webapp"];
const WEBAPP_KEYWORDS = new Set(["signalk-embeddable-webapp", "signalk-webapp"]);
const REGISTRY_URL = "https://signalk.org/signalk-plugin-registry/index.json";
const REGISTRY_PAGE = "https://signalk.org/signalk-plugin-registry/";
const TIMEOUT_MS = 60_000;
const ACTIVE_DAYS = 90;

const OFFICIAL = SIGNALK_GROUPS[0];
const UNCATEGORIZED = SIGNALK_GROUPS.at(-1);

async function fetchJson(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

// Same paging as the App Store's searchByKeyword: npm's `total` is an estimate, so stop on
// an empty page as well.
async function searchNpm(keyword) {
  const results = [];
  for (let page = 0; page < 20; page++) {
    const url = `https://registry.npmjs.org/-/v1/search?size=250&from=${results.length}&text=keywords:${keyword}`;
    const { objects, total } = await fetchJson(url);
    if (!Array.isArray(objects) || objects.length === 0) break;
    results.push(...objects);
    if (results.length >= total) break;
  }
  return results;
}

// App Store category names for a package, following getCategories() in signalk-server.
function categoryKeywords(pkg) {
  const defaults = DEFAULT_MODULE_CAT_KEYWORDS[pkg.name] ?? [];
  if (defaults.includes(DEPRECATED)) return null;
  const own = (pkg.keywords ?? []).filter((keyword) => keyword in CATEGORIES);
  return [...new Set(own.length ? own : defaults.filter((keyword) => keyword in CATEGORIES))];
}

// Escape characters that would turn a free-text npm description into Markdown or HTML.
function escapeMarkdown(text) {
  return text
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[\\`*_[\]<>|#]/g, "\\$&");
}

const dateFormat = new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });

function formatEntry(plugin, { showOfficial = true } = {}) {
  const { name, description, version, date, webapp, score, githubUrl } = plugin;
  const npmUrl = `https://www.npmjs.com/package/${name}`;
  const facts = [
    showOfficial && plugin.official ? "official" : null,
    webapp ? "webapp" : null,
    `v${version}`,
    date ? `published ${dateFormat.format(date)}` : null,
    score === undefined ? "not yet scored" : `score ${score}`,
  ].filter(Boolean);
  const source = githubUrl ? ` · [source](${githubUrl})` : "";
  const text = description ? ` - ${escapeMarkdown(description)}` : "";
  return `- [${name}](${npmUrl})${text} *(${facts.join(", ")})*${source}`;
}

function writePage(path, title, description, body) {
  const frontmatter = [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    "<!-- Generated by scripts/build-signalk-plugins.mjs from npm and the SignalK Plugin Registry — do not edit directly. -->",
    "",
  ].join("\n");
  writeFileSync(path, frontmatter + body.trim() + "\n");
}

const INDEX_TITLE = "SignalK Plugins";
const INDEX_DESCRIPTION = "SignalK server plugins and webapps from the App Store, by category.";

async function loadPlugins() {
  const [searches, registry] = await Promise.all([
    Promise.all(SEARCH_KEYWORDS.map(searchNpm)),
    fetchJson(REGISTRY_URL).catch((error) => {
      console.warn(`build-signalk-plugins: no registry scores (${error.message})`);
      return null;
    }),
  ]);

  const scores = new Map((registry?.plugins ?? []).map((entry) => [entry.name, entry]));
  const packages = new Map();
  for (const { package: pkg } of searches.flat()) {
    if (pkg?.name && !packages.has(pkg.name)) packages.set(pkg.name, pkg);
  }

  const plugins = [];
  for (const pkg of packages.values()) {
    const categories = categoryKeywords(pkg);
    if (categories === null) continue; // deprecated
    const keywords = pkg.keywords ?? [];
    const scored = scores.get(pkg.name);
    plugins.push({
      name: pkg.name,
      description: pkg.description ?? "",
      version: pkg.version,
      date: pkg.date ? new Date(pkg.date) : null,
      official: pkg.name.startsWith("@signalk/"),
      webapp: scored?.webapp ?? (keywords.some((k) => WEBAPP_KEYWORDS.has(k)) && !keywords.includes("signalk-node-server-plugin")),
      score: scored?.composite_stable,
      badges: scored?.badges_stable ?? [],
      testStatus: scored?.test_status,
      githubUrl: scored?.github_url,
      categories,
    });
  }
  // Sort by name ignoring the npm scope, so "@signalk/charts-plugin" files under C.
  const sortKey = (name) => name.replace(/^@[^/]+\//, "");
  plugins.sort((a, b) => sortKey(a.name).localeCompare(sortKey(b.name), "en", { sensitivity: "base" }));
  return { plugins, registry };
}

mkdirSync(pagesDir, { recursive: true });
rmSync(dataPath, { force: true });
const indexPath = resolve(docsDir, "signalk-plugins.md");

let data;
try {
  data = await loadPlugins();
} catch (error) {
  console.warn(`build-signalk-plugins: couldn't fetch plugin data, writing a placeholder (${error.message})`);
  writePage(
    indexPath,
    INDEX_TITLE,
    INDEX_DESCRIPTION,
    "The plugin list couldn't be fetched when this copy of the site was built. Browse the **Appstore** in your SignalK server's Admin UI instead.",
  );
  process.exit(0);
}

const { plugins, registry } = data;
const generated = registry ? new Date(registry.generated) : new Date();
const asOf = dateFormat.format(generated);
const activeSince = Date.now() - ACTIVE_DAYS * 24 * 3600 * 1000;

const groups = SIGNALK_GROUPS.map((group) => ({
  ...group,
  plugins: plugins.filter((p) =>
    group === OFFICIAL ? p.official : group === UNCATEGORIZED ? p.categories.length === 0 : p.categories.includes(group.keyword),
  ),
}));

// Page title and meta description, phrased the way people search ("SignalK AIS plugins").
const pageTitle = (name) => `${name} SignalK Plugins`;
const pageDescription = ({ name, description, plugins: members }) =>
  `${members.length} ${name === UNCATEGORIZED.name ? "uncategorized" : name} SignalK server plugins and webapps from the App Store. ${description}`;

const scoreNote = `Scores out of 100 come from the [SignalK Plugin Registry](${REGISTRY_PAGE}), which installs, loads and activates each plugin on a real server, and checks its tests and security audit.`;

for (const group of groups) {
  const { name, slug, description, plugins: members } = group;
  // Links to every other category, so each page is reachable from every other one.
  const otherCategories = groups
    .map((g) => (g.slug === slug ? `**${g.name}**` : `[${g.name}](../${g.slug}/)`))
    .join(" · ");
  const body = [
    description,
    "",
    `${members.length} packages, as of ${asOf}. Install them from the **Appstore** in your SignalK server's Admin UI. ${scoreNote}`,
    "",
    `[All categories](../): ${otherCategories}`,
    "",
    members.map((p) => formatEntry(p, { showOfficial: slug !== OFFICIAL.slug })).join("\n"),
  ].join("\n");
  writePage(resolve(pagesDir, `${slug}.md`), pageTitle(name), pageDescription(group), body);
}

const active = plugins.filter((p) => p.date && p.date.getTime() >= activeSince).length;
const categoryList = groups
  .map(({ name, slug, description, plugins: members }) => `- [${name}](./${slug}/) - ${description} (${members.length})`)
  .join("\n");

const indexBody = `The SignalK server's **Appstore** lists ${plugins.length} plugins and webapps, but only inside the Admin UI. These pages list the same packages, grouped by the Appstore's own categories, so you can browse them from anywhere, including offline in the Boat Tech Directory's SignalK plugin.

The list is rebuilt every week from npm and the [SignalK Plugin Registry](${REGISTRY_PAGE}). This copy is as of ${asOf}. ${active} packages were published in the last ${ACTIVE_DAYS} days.

A package can belong to more than one category, so it may appear on more than one page. Packages the SignalK server marks as deprecated are left out.

The same data is available as JSON at [signalk-plugins.json](../signalk-plugins.json).

## Categories

${categoryList}
`;
writePage(
  indexPath,
  INDEX_TITLE,
  `Browse ${plugins.length} SignalK server plugins and webapps from the SignalK App Store by category, with SignalK Plugin Registry scores. Updated weekly.`,
  indexBody,
);

// Category names per package, for the JSON. Official is a grouping here, not an App Store
// category, so it's a separate flag.
const categoryNames = (plugin) =>
  plugin.categories.length ? plugin.categories.map((keyword) => CATEGORIES[keyword][0]) : [UNCATEGORIZED.name];

const json = {
  name: "SignalK Plugins",
  description:
    "SignalK server plugins and webapps from the SignalK App Store, with App Store categories and SignalK Plugin Registry scores. Deprecated packages are left out.",
  homepage: `${SITE}/signalk-plugins/`,
  sources: ["https://registry.npmjs.org", REGISTRY_URL],
  generated: generated.toISOString(),
  count: plugins.length,
  categories: groups.map(({ name, slug, description, plugins: members }) => ({
    name,
    description,
    count: members.length,
    url: `${SITE}/signalk-plugins/${slug}/`,
  })),
  plugins: plugins.map((p) => ({
    name: p.name,
    description: p.description,
    version: p.version,
    published: p.date?.toISOString() ?? null,
    official: p.official,
    webapp: p.webapp,
    categories: categoryNames(p),
    score: p.score ?? null,
    badges: p.badges,
    testStatus: p.testStatus ?? null,
    npmUrl: `https://www.npmjs.com/package/${p.name}`,
    sourceUrl: p.githubUrl ?? null,
  })),
};
writeFileSync(dataPath, JSON.stringify(json, null, 2) + "\n");

console.log(`Wrote signalk-plugins pages: ${plugins.length} packages in ${groups.length} categories.`);
